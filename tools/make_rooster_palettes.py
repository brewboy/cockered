#!/usr/bin/env python3
"""Generate a 4-colour palette per species for Rooster Edition.

Usage: tools/make_rooster_palettes.py [SRC_DIR]

For each species, the colour front in SRC_DIR/colour (default gfx/rooster_src)
is compared with its Game Boy front: the pixels drawn in light grey and dark grey
pick the palette's two middle colours. Comb, wattle and beak colours are left out
unless they make up most of a shade, so a bird's body sets its colour.

Writes data/sgb/rooster_palettes.asm (one RGB line per species, appended to
SuperPalettes) and data/pokemon/palettes.asm (MonsterPalettes). Run from the
repository root.
"""

import glob
import os
import re
import sys
from collections import Counter

from PIL import Image

SKIP = {83}  # Farfetch'd keeps its original palette
OVERRIDE = {150: '150_lab_bred_goose.png'}
ACCENTS = {(214, 40, 40), (145, 26, 30), (238, 190, 70), (161, 125, 53), (20, 20, 24)}
WHITE, BLACK = (31, 29, 31), (3, 2, 2)  # colours 0 and 3, as in the other SGB palettes


def front(src, dex, kind):
	if dex in OVERRIDE:
		return os.path.join(src, kind, OVERRIDE[dex])
	return sorted(glob.glob(os.path.join(src, kind, f'{dex:03}_*.png')))[0]


def pick(counts):
	"""The dominant colour of a shade, nudged towards the mean of the rest."""
	body = Counter({c: n for c, n in counts.items() if c not in ACCENTS})
	if not body or sum(body.values()) < .25 * sum(counts.values()):
		body = counts
	dom = body.most_common(1)[0][0]
	total = sum(body.values())
	mean = [sum(c[i] * n for c, n in body.items()) / total for i in range(3)]
	return tuple(round(.7 * d + .3 * m) for d, m in zip(dom, mean))


def palette(src, dex):
	colour = Image.open(front(src, dex, 'colour')).convert('RGBA')
	grey = Image.open(front(src, dex, 'gameboy')).convert('L')
	shades = {170: Counter(), 85: Counter()}
	for c, g in zip(colour.get_flattened_data(), grey.get_flattened_data()):
		if c[3] and g in shades:
			shades[g][c[:3]] += 1
	light = pick(shades[170]) if shades[170] else (200, 200, 200)
	dark = pick(shades[85]) if shades[85] else tuple(v // 2 for v in light)
	return [tuple(min(31, round(v * 31 / 255)) for v in c) for c in (light, dark)]


def main():
	src = sys.argv[1] if len(sys.argv) > 1 else 'gfx/rooster_src'
	table = open('data/pokemon/palettes.asm').read()
	rows = re.findall(r'\tdb (PAL_\w+)\s*; (\w+)', table)
	assert len(rows) == 152, len(rows)  # MISSINGNO + 151

	pals, out = [], ['MonsterPalettes:', '\ttable_width 1']
	for dex, (old, name) in enumerate(rows):
		if dex == 0 or dex in SKIP:
			out.append(f'\tdb {old:<16} ; {name}')
			continue
		out.append(f'\tdb PAL_ROOSTER + {len(pals):<3} ; {name}')
		pals.append((name, palette(src, dex)))
	out.append('\tassert_table_length NUM_POKEMON + 1')
	open('data/pokemon/palettes.asm', 'w').write('\n'.join(out) + '\n')

	rgb = lambda c: ','.join(f'{v:02}' for v in c)
	lines = ['; Rooster Edition species palettes, generated by tools/make_rooster_palettes.py.',
		'; Entries follow PAL_ROOSTER; MonsterPalettes points each species at its own.']
	for name, (light, dark) in pals:
		lines.append(f'\tRGB {rgb(WHITE)}, {rgb(light)}, {rgb(dark)}, {rgb(BLACK)} ; {name}')
	open('data/sgb/rooster_palettes.asm', 'w').write('\n'.join(lines) + '\n')
	print(f'{len(pals)} species palettes written')


if __name__ == '__main__':
	main()
